import { cp, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';

const owner = 'benson';
const root = process.cwd();
const releaseSha = process.env.VELLUM_UI_SHA || git(['rev-parse', 'HEAD']).trim();
const shortSha = releaseSha.slice(0, 12);
const packageSpec = `git+https://github.com/benson/vellum-ui.git#${releaseSha}`;
const shouldMerge = process.env.VELLUM_RELEASE_MERGE === '1';

if (!process.env.GH_TOKEN) {
  throw new Error('GH_TOKEN must be set to BENSON_RELEASE_TOKEN for cross-repo releases.');
}

git(['rev-parse', '--verify', releaseSha]);
run('npm', ['run', 'build']);

const dist = join(root, 'dist');
const workspace = await mkdtemp(join(tmpdir(), `vellum-release-${shortSha}-`));

const consumers = [
  {
    repo: `${owner}/benson.github.io`,
    base: 'master',
    name: 'homepage',
    checkCommand: ['npm', ['test']],
    waitForChecks: false,
    update: updateHomepage,
  },
  {
    repo: `${owner}/poolbuilder`,
    base: 'main',
    name: 'poolbuilder',
    checkCommand: ['npm', ['test']],
    update: updatePoolBuilder,
  },
  {
    repo: `${owner}/biblioplex`,
    base: 'master',
    name: 'biblioplex',
    checkCommand: ['npm', ['run', 'check']],
    waitForChecks: false,
    update: updateBiblioplex,
    afterMerge: () => gh(['workflow', 'run', 'Deploy Cloudflare', '--repo', `${owner}/biblioplex`, '--ref', 'master']),
  },
];

for (const consumer of consumers) {
  await releaseConsumer(consumer);
}

async function releaseConsumer(consumer) {
  const branch = `vellum-ui-${shortSha}`;
  const path = join(workspace, consumer.name);
  gh(['repo', 'clone', consumer.repo, path, '--', '--depth', '1']);
  run('git', ['checkout', '-b', branch], { cwd: path });
  configureGit(path, consumer.repo);

  await consumer.update(path);

  if (!hasChanges(path)) {
    console.log(`${consumer.repo}: already at ${shortSha}`);
    return;
  }

  run('git', ['add', '-A'], { cwd: path });
  run('git', ['commit', '-m', `Update Vellum UI to ${shortSha}`], { cwd: path });
  run('git', ['push', '-u', 'origin', branch], { cwd: path });

  const body = [
    `Updates Vellum UI to \`${releaseSha}\`.`,
    '',
    'Generated by the Vellum UI release workflow.',
  ].join('\n');
  const prUrl = gh([
    'pr',
    'create',
    '--repo',
    consumer.repo,
    '--base',
    consumer.base,
    '--head',
    branch,
    '--title',
    `Update Vellum UI to ${shortSha}`,
    '--body',
    body,
  ]).trim();
  console.log(`${consumer.repo}: ${prUrl}`);

  if (!shouldMerge) return;
  if (consumer.checkCommand) run(consumer.checkCommand[0], consumer.checkCommand[1], { cwd: path });
  if (consumer.waitForChecks !== false) waitForPrChecks(consumer.repo, prUrl);
  gh(['pr', 'merge', prUrl, '--squash', '--delete-branch']);
  if (consumer.afterMerge) consumer.afterMerge();
}

async function updateHomepage(path) {
  run('npm', ['ci'], { cwd: path });
  await rm(join(path, 'vellum-ui'), { recursive: true, force: true });
  await mkdir(join(path, 'vellum-ui'), { recursive: true });
  await cp(dist, join(path, 'vellum-ui'), { recursive: true, force: true });
  await rm(join(path, 'vellum-ui', 'design-system.html'), { force: true });
  await writeDesignSystemPage(path);
  await writeRedirect(path, join('benson-ui', 'design-system.html'));
  await writeRedirect(path, join('benson-ui', 'design-system', 'index.html'));
  await writeRedirect(path, join('BensonUI', 'design-system.html'));
  await writeRedirect(path, join('BensonUI', 'design-system', 'index.html'));

  const indexPath = join(path, 'index.html');
  const index = await readFile(indexPath, 'utf8');
  await writeFile(
    indexPath,
    index
      .replaceAll('/benson-ui/design-system/', '/vellum-ui/design-system/')
      .replaceAll('benson ui', 'vellum ui')
      .replaceAll('Benson UI', 'Vellum UI'),
  );
}

