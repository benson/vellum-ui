import { cp, mkdtemp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join, relative } from 'node:path';
import { spawnSync } from 'node:child_process';

const owner = 'benson';
const root = process.cwd();
const triggerSha = process.env.VELLUM_UI_SHA || git(['rev-parse', 'HEAD']).trim();
// Auto-merge is the default; set VELLUM_RELEASE_MERGE=0 for a review-only run.
const shouldMerge = process.env.VELLUM_RELEASE_MERGE !== '0';

if (!process.env.GH_TOKEN) {
  throw new Error('GH_TOKEN must be set to BENSON_RELEASE_TOKEN for cross-repo releases.');
}

git(['rev-parse', '--verify', triggerSha]);

// Bump Vellum's own package version before releasing. npm treats a git
// dependency as already satisfied when the package `version` is unchanged, so a
// pin bump alone (the commit SHA moves, version stays 0.1.0) silently leaves
// consumers' local node_modules stale — every `npm install` skips the refetch,
// and anyone reading that stale copy gets an old API. Committing a patch bump
// back to main (with [skip ci] so Check -> Release doesn't re-fire) makes each
// release a distinct version, so consumers' npm actually reinstalls. Falls back
// to the un-bumped SHA if the self-push can't land, so a token or branch-
// protection hiccup degrades to today's behavior rather than breaking releases.
const releaseSha = await resolveReleaseSha(triggerSha);
const shortSha = releaseSha.slice(0, 12);
const packageSpec = `git+https://github.com/benson/vellum-ui.git#${releaseSha}`;

run('npm', ['run', 'build']);

const dist = join(root, 'dist');
const workspace = await mkdtemp(join(tmpdir(), `vellum-release-${shortSha}-`));

const consumers = [
  {
    repo: `${owner}/benson.github.io`,
    base: 'master',
    name: 'homepage',
    checkCommand: ['npm', ['test']],
    waitForChecks: false,
    update: updateHomepage,
  },
  {
    repo: `${owner}/poolbuilder`,
    base: 'main',
    name: 'poolbuilder',
    checkCommand: ['npm', ['test']],
    update: updateVendoredConsumer,
  },
  {
    repo: `${owner}/packcracker`,
    base: 'main',
    name: 'packcracker',
    waitForChecks: false,
    update: updateVendoredConsumer,
  },
  {
    repo: `${owner}/biblioplex`,
    base: 'master',
    name: 'biblioplex',
    checkCommand: ['npm', ['run', 'check']],
    waitForChecks: false,
    update: updateBiblioplex,
    afterMerge: () => gh(['workflow', 'run', 'Deploy Cloudflare', '--repo', `${owner}/biblioplex`, '--ref', 'master']),
  },
];

for (const consumer of consumers) {
  await releaseConsumer(consumer);
}

async function releaseConsumer(consumer) {
  const branch = `vellum-ui-${shortSha}`;
  const path = join(workspace, consumer.name);
  gh(['repo', 'clone', consumer.repo, path, '--', '--depth', '1']);
  run('git', ['checkout', '-b', branch], { cwd: path });
  configureGit(path, consumer.repo);

  await consumer.update(path);

  if (!hasChanges(path)) {
    console.log(`${consumer.repo}: already at ${shortSha}`);
    return;
  }

  run('git', ['add', '-A'], { cwd: path });
  run('git', ['commit', '-m', `Update Vellum UI to ${shortSha}`], { cwd: path });
  run('git', ['push', '-u', 'origin', branch], { cwd: path });

  const body = [
    `Updates Vellum UI to \`${releaseSha}\`.`,
    '',
    'Generated by the Vellum UI release workflow.',
  ].join('\n');
  const prUrl = gh([
    'pr',
    'create',
    '--repo',
    consumer.repo,
    '--base',
    consumer.base,
    '--head',
    branch,
    '--title',
    `Update Vellum UI to ${shortSha}`,
    '--body',
    body,
  ]).trim();
  console.log(`${consumer.repo}: ${prUrl}`);

  if (!shouldMerge) return;
  if (consumer.checkCommand) run(consumer.checkCommand[0], consumer.checkCommand[1], { cwd: path });
  if (consumer.waitForChecks !== false) waitForPrChecks(consumer.repo, prUrl);
  gh(['pr', 'merge', prUrl, '--squash', '--delete-branch']);
  if (consumer.afterMerge) consumer.afterMerge();
}

async function updateHomepage(path) {
  run('npm', ['ci'], { cwd: path });
  await rm(join(path, 'vellum-ui'), { recursive: true, force: true });
  await mkdir(join(path, 'vellum-ui'), { recursive: true });
  await cp(dist, join(path, 'vellum-ui'), { recursive: true, force: true });
  await rm(join(path, 'vellum-ui', 'design-system.html'), { force: true });
  await writeDesignSystemPage(path);
}

async function writeDesignSystemPage(path) {
  const pagePath = join(path, 'vellum-ui', 'design-system', 'index.html');
  await mkdir(dirname(pagePath), { recursive: true });
  await writeFile(
    pagePath,
    `<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Vellum UI Design System</title>
    <meta name="description" content="Shared design system for Benson Perry apps." />
    <link rel="canonical" href="https://bensonperry.com/vellum-ui/design-system/" />
    <link rel="icon" type="image/svg+xml" href="../demo/favicon.svg?v=${shortSha}" />
    <link rel="stylesheet" href="../vellum-ui.css?v=${shortSha}" />
  </head>
  <body class="vui-app vui-design-system-page design-system-page">
    <main id="designSystemMount" class="vui-design-system ds-page-wrap"></main>
    <script type="module" src="../demo/designSystem.js?v=${shortSha}"></script>
  </body>
</html>
`,
  );
}

// poolbuilder and packcracker both vendor dist via their sync:ui script.
async function updateVendoredConsumer(path) {
  await setPackageDependency(path);
  run('npm', ['install'], { cwd: path });
  await sanitizePackageLock(path);
  run('npm', ['run', 'sync:ui'], { cwd: path });
  await bumpVendoredCacheBust(path);
}

// GH Pages serves these sites with max-age=600, so a pin bump that rewrites
// the vendored vellum-ui.css needs its cache-bust param stamped too or the
// stale sheet lingers for up to 10 minutes. Stamp the release sha.
async function bumpVendoredCacheBust(path) {
  const indexPath = join(path, 'index.html');
  if (!existsSync(indexPath)) return;
  const source = await readFile(indexPath, 'utf8');
  const next = source.replace(/(vendor\/vellum-ui\/vellum-ui\.css\?v=)[\w-]*/g, `$1${shortSha}`);
  if (next !== source) await writeFile(indexPath, next);
}

async function updateBiblioplex(path) {
  await setPackageDependency(path);
  run('npm', ['install'], { cwd: path });
  await sanitizePackageLock(path);
}

async function setPackageDependency(path) {
  const packagePath = join(path, 'package.json');
  const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
  packageJson.dependencies ||= {};
  packageJson.dependencies['@benson/vellum-ui'] = packageSpec;
  await writeFile(packagePath, `${JSON.stringify(packageJson, null, 2)}\n`);
}

async function replaceInFile(path, replacements) {
  if (!existsSync(path)) return;
  let source = await readFile(path, 'utf8');
  let next = source;
  for (const [from, to] of replacements) next = next.replaceAll(from, to);
  if (next !== source) await writeFile(path, next);
}

async function sanitizePackageLock(path) {
  await replaceInFile(join(path, 'package-lock.json'), [
    ['git+ssh://git@github.com/benson/vellum-ui.git', 'git+https://github.com/benson/vellum-ui.git'],
    ['ssh://git@github.com/benson/vellum-ui.git', 'https://github.com/benson/vellum-ui.git'],
  ]);
}

function waitForPrChecks(repo, prUrl) {
  const timeoutMs = Number(process.env.VELLUM_RELEASE_CHECK_TIMEOUT_MS || 30 * 60 * 1000);
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    const result = spawnSync('gh', ['pr', 'checks', prUrl, '--repo', repo, '--json', 'name,state,bucket'], {
      encoding: 'utf8',
      stdio: ['ignore', 'pipe', 'pipe'],
    });
    if (result.status !== 0) {
      console.log(`${repo}: checks unavailable yet`);
      sleep(15000);
      continue;
    }
    const checks = JSON.parse(result.stdout || '[]');
    if (!checks.length) {
      console.log(`${repo}: no checks reported yet`);
      sleep(15000);
      continue;
    }
    const failing = checks.filter((check) => {
      const bucket = String(check.bucket || '').toLowerCase();
      const state = String(check.state || '').toUpperCase();
      return ['fail', 'cancel'].includes(bucket) || ['FAILURE', 'CANCELLED', 'TIMED_OUT', 'ACTION_REQUIRED'].includes(state);
    });
    if (failing.length) throw new Error(`${repo}: failing checks: ${failing.map((check) => check.name).join(', ')}`);
    const pending = checks.filter((check) => {
      const bucket = String(check.bucket || '').toLowerCase();
      const state = String(check.state || '').toUpperCase();
      return !['pass', 'skipping'].includes(bucket) && !['SUCCESS', 'SKIPPED'].includes(state);
    });
    if (!pending.length) return;
    console.log(`${repo}: waiting on ${pending.map((check) => check.name).join(', ')}`);
    sleep(15000);
  }
  throw new Error(`${repo}: timed out waiting for PR checks`);
}

async function resolveReleaseSha(triggerSha) {
  try {
    return await bumpVellumVersion();
  } catch (error) {
    console.warn(
      `Vellum version bump skipped: ${error.message}\n` +
        `Releasing ${triggerSha.slice(0, 12)} without a version bump — consumers' local ` +
        `node_modules may stay stale until reinstalled. Check BENSON_RELEASE_TOKEN write ` +
        `access to vellum-ui and that main allows direct pushes.`,
    );
    return triggerSha;
  }
}

// Increment Vellum's patch version and commit it back to main so each release is
// a distinct npm version (see the note at the call site). [skip ci] keeps the
// bump commit from re-triggering Check -> Release.
async function bumpVellumVersion() {
  const packagePath = join(root, 'package.json');
  const packageJson = JSON.parse(await readFile(packagePath, 'utf8'));
  const [major, minor, patch] = String(packageJson.version).split('.').map(Number);
  packageJson.version = `${major}.${minor}.${(patch || 0) + 1}`;
  await writeFile(packagePath, `${JSON.stringify(packageJson, null, 2)}\n`);
  // Commit + push over this checkout's own origin, which actions/checkout already
  // authenticated with GITHUB_TOKEN — so the push relies on the workflow's
  // `contents: write` permission, not the cross-repo PAT (whose scope over
  // vellum-ui itself isn't guaranteed). GITHUB_TOKEN-authored pushes don't
  // re-trigger workflows, and the [skip ci] tag is a second guard against a
  // Check -> Release loop.
  run('git', ['config', 'user.name', 'github-actions[bot]'], { cwd: root });
  run(
    'git',
    ['config', 'user.email', '41898282+github-actions[bot]@users.noreply.github.com'],
    { cwd: root },
  );
  run('git', ['add', 'package.json'], { cwd: root });
  run('git', ['commit', '-m', `Release ${packageJson.version} [skip ci]`], { cwd: root });
  run('git', ['push', 'origin', 'HEAD:main'], { cwd: root });
  console.log(`Vellum UI version bumped to ${packageJson.version}`);
  return git(['rev-parse', 'HEAD']).trim();
}

function configureGit(cwd, repo) {
  run('git', ['config', 'user.name', 'github-actions[bot]'], { cwd });
  run('git', ['config', 'user.email', '41898282+github-actions[bot]@users.noreply.github.com'], { cwd });
  run(
    'git',
    ['remote', 'set-url', 'origin', `https://x-access-token:${encodeURIComponent(process.env.GH_TOKEN)}@github.com/${repo}.git`],
    { cwd, sensitive: true },
  );
}

function hasChanges(cwd) {
  return run('git', ['status', '--porcelain'], { cwd, capture: true }).trim().length > 0;
}

function gh(args) {
  return run('gh', args, { capture: true });
}

function git(args) {
  return run('git', args, { capture: true });
}

function run(command, args, options = {}) {
  const result = spawnSync(command, args, {
    cwd: options.cwd || root,
    encoding: 'utf8',
    env: { ...process.env, GH_TOKEN: process.env.GH_TOKEN },
    stdio: options.capture ? ['ignore', 'pipe', 'pipe'] : 'inherit',
  });
  if (result.status !== 0) {
    const detail = [result.stdout, result.stderr].filter(Boolean).join('\n');
    const commandText = options.sensitive ? `${command} [redacted]` : `${command} ${args.join(' ')}`;
    throw new Error(`${commandText} failed${detail ? `\n${detail}` : ''}`);
  }
  return result.stdout || '';
}

function sleep(ms) {
  Atomics.wait(new Int32Array(new SharedArrayBuffer(4)), 0, 0, ms);
}
